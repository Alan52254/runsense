import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : await import('playwright');
const out = process.env.QA_OUTPUT ?? '.scratch/frontend-redesign-v2/after';
await mkdir(out,{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.QA_URL ?? 'http://127.0.0.1:5180');
await page.locator('.persona-button').filter({hasText:'runner.tokyo@'}).click();
await page.locator('button[type=submit]').click();
await page.waitForURL('**/app');
await page.waitForTimeout(1800);
await writeFile(out+'/dashboard.txt',await page.locator('body').innerText());
await page.screenshot({path:out+'/dashboard-desktop.png',fullPage:true});
console.log((await page.locator('body').innerText()).slice(0,4500));
console.log('PAGE_ERRORS',errors);
await browser.close();
